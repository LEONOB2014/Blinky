"""Generate the AI-lexicon BigQuery scripts from contracts/ai_lexicon.yaml.

    uv run python pipelines/ingest/gen_ai_sql.py                      # bq_sql/s15_*, s16_*
    uv run python pipelines/ingest/gen_ai_sql.py --lexicon stub.yaml  # any lexicon file

A topic is ``ai:<id>``. An article (ring 1, ``segment = 'ai'``) counts for an entry when any of
its patterns matches ``txt`` (lowercased title + URL) or one of its ``gdelt_orgs`` aliases is in
``orgs``. Each entry's patterns are joined into one RE2 alternation, and the entries are inlined
as an ``ARRAY<STRUCT<id, re, orgs>>`` that the scripts UNNEST: one REGEXP_CONTAINS per entry and
article.

- S15 writes ``radar.article_topic_ai`` (one row per article and matched entry, for S13/S14 and
  the evidence) and ``radar.topic_ai_daily`` with the exact ``topic_daily`` schema, so scoring,
  the window and the backtest read it unchanged. No 20-article floor: the lexicon is curated.
- S16 writes ``radar.edges_ai_weekly``: co-mentions of two entries in one article per Monday
  week, for all languages (``lang_bucket = 'all'``) and per language bucket, with the columns of
  edges_weekly. It repeats the match instead of reading S15's table, so it dry-runs on its own.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
LEXICON = REPO_ROOT / "contracts" / "ai_lexicon.yaml"
S15 = REPO_ROOT / "bq_sql" / "s15_topic_ai_daily.sql"
S16 = REPO_ROOT / "bq_sql" / "s16_edges_ai_weekly.sql"

PREFIXES = (
    "lab", "model", "product", "tech", "infra", "research", "biz", "policy", "risk", "critic",
    "culture",
)  # fmt: skip
ID_RE = re.compile(rf"^(?:{'|'.join(PREFIXES)}):[a-z0-9][a-z0-9_.+-]*$")


def load_entries(path: Path) -> list[dict]:
    """Entries of a lexicon file, checked for what the SQL relies on."""
    doc = yaml.safe_load(path.read_text(encoding="utf-8"))
    entries = doc.get("entries") or []
    seen: set[str] = set()
    problems: list[str] = []
    for i, e in enumerate(entries):
        eid = e.get("id", "")
        if not ID_RE.match(eid):
            problems.append(f"entry {i}: bad id {eid!r}")
        if eid in seen:
            problems.append(f"entry {i}: duplicate id {eid!r}")
        seen.add(eid)
        patterns = e.get("patterns") or []
        orgs = e.get("gdelt_orgs") or []
        if not patterns and not orgs:
            problems.append(f"{eid}: no patterns and no gdelt_orgs")
        for p in patterns:
            if '"""' in p:
                problems.append(f"{eid}: pattern contains a triple quote")
            try:
                re.compile(p)
            except re.error as err:
                problems.append(f"{eid}: pattern {p!r} does not compile ({err})")
        for o in orgs:
            if o != o.lower() or o != o.strip():
                problems.append(f"{eid}: gdelt_orgs alias {o!r} must be lowercase and trimmed")
    if not entries:
        problems.append("no entries")
    if problems:
        raise ValueError("lexicon problems:\n  " + "\n  ".join(problems))
    return entries


def _string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lexicon_array(entries: list[dict]) -> str:
    """The entries as a typed BigQuery array literal of (id, re, orgs)."""
    rows = []
    for e in entries:
        patterns = e.get("patterns") or []
        regex = "|".join(f"(?:{p})" for p in patterns)
        re_sql = f'r"""{regex}"""' if regex else "NULL"
        orgs = ", ".join(_string(o) for o in (e.get("gdelt_orgs") or []))
        rows.append(f"    ({_string(e['id'])}, {re_sql}, ARRAY<STRING>[{orgs}])")
    return "ARRAY<STRUCT<id STRING, re STRING, orgs ARRAY<STRING>>>[\n" + ",\n".join(rows) + "\n  ]"


def match_ctes(entries: list[dict], columns: str) -> str:
    """CTEs ``lex`` and ``hits``: one row per ring-1 article and matched entry."""
    return f"""lex AS (
  SELECT * FROM UNNEST({lexicon_array(entries)})
),
hits AS (
  SELECT DISTINCT {columns}, CONCAT('ai:', l.id) AS topic_id
  FROM `radar.article_segment` AS a
  CROSS JOIN lex AS l
  WHERE a.segment = 'ai'
    AND (
      (l.re IS NOT NULL AND REGEXP_CONTAINS(a.txt, l.re))
      OR EXISTS (SELECT 1 FROM UNNEST(a.orgs) AS o WHERE o IN UNNEST(l.orgs))
    )
)"""


def header(n: int, source: Path) -> str:
    try:
        shown = source.resolve().relative_to(REPO_ROOT)
    except ValueError:
        shown = source.name
    return (
        f"-- Generated by pipelines/ingest/gen_ai_sql.py from {shown} ({n} entries).\n"
        "-- Do not edit by hand: change the lexicon and regenerate.\n"
    )


def s15(entries: list[dict], source: Path) -> str:
    cols = "a.gkg_id, a.dt, a.lang_bucket, a.source, a.tone, a.polarity"
    return (
        header(len(entries), source)
        + f"""-- S15: radar.article_topic_ai (article -> AI-lexicon topic) and radar.topic_ai_daily,
-- the schema of topic_daily (contracts/topic_daily.schema.json) for topics 'ai:<id>'.
-- Days with no article for a topic have no row; is_missing days keep their row with
-- share_of_day NULL (the daily_totals join of S11). No article floor.
CREATE OR REPLACE TABLE `radar.article_topic_ai`
PARTITION BY dt
CLUSTER BY topic_id AS
WITH {match_ctes(entries, cols)}
SELECT
  gkg_id, dt, DATE_TRUNC(dt, WEEK(MONDAY)) AS week, lang_bucket, source, tone, polarity,
  topic_id
FROM hits;

CREATE OR REPLACE TABLE `radar.topic_ai_daily`
PARTITION BY dt
CLUSTER BY topic_id, lang_bucket AS
WITH daily AS (
  SELECT
    topic_id, dt, lang_bucket,
    COUNT(DISTINCT gkg_id) AS n_articles,
    AVG(tone) AS mean_tone,
    AVG(polarity) AS mean_polarity
  FROM `radar.article_topic_ai`
  GROUP BY topic_id, dt, lang_bucket
)
SELECT
  d.topic_id,
  d.dt,
  d.lang_bucket,
  'ai' AS segment,
  d.n_articles,
  IF(IFNULL(t.is_missing, TRUE), NULL, SAFE_DIVIDE(d.n_articles, t.n_all)) AS share_of_day,
  d.mean_tone,
  d.mean_polarity,
  IFNULL(t.is_missing, TRUE) AS is_missing
FROM daily AS d
LEFT JOIN `radar.daily_totals` AS t
  ON t.dt = d.dt AND t.lang_bucket = d.lang_bucket;
"""
    )


def s16(entries: list[dict], source: Path) -> str:
    cols = "a.gkg_id, a.dt, a.lang_bucket, a.source"
    return (
        header(len(entries), source)
        + f"""-- S16: radar.edges_ai_weekly, co-mentions of two AI-lexicon topics in one ring-1
-- article per Monday week, for all languages (lang_bucket 'all') and per language
-- bucket. Columns follow edges_weekly (S4b): n articles with both, n_src distinct
-- outlets, nx / ny articles with each topic, n_docs ring-1 articles with any lexicon
-- topic that week and bucket, npmi. No floor on n: the lexicon is curated.
CREATE OR REPLACE TABLE `radar.edges_ai_weekly`
CLUSTER BY lang_bucket, x, y AS
WITH {match_ctes(entries, cols)},
e AS (
  SELECT DISTINCT
    gkg_id, DATE_TRUNC(dt, WEEK(MONDAY)) AS wk, lang_bucket, source, topic_id AS ent
  FROM hits
  UNION ALL
  SELECT DISTINCT gkg_id, DATE_TRUNC(dt, WEEK(MONDAY)), 'all', source, topic_id FROM hits
),
pairs AS (
  SELECT
    a.wk, a.lang_bucket, a.ent AS x, b.ent AS y, COUNT(*) AS n,
    COUNT(DISTINCT a.source) AS n_src
  FROM e AS a
  JOIN e AS b ON a.gkg_id = b.gkg_id AND a.lang_bucket = b.lang_bucket AND a.ent < b.ent
  GROUP BY a.wk, a.lang_bucket, x, y
),
deg AS (
  SELECT wk, lang_bucket, ent, COUNT(*) AS nx FROM e GROUP BY wk, lang_bucket, ent
),
tot AS (
  SELECT wk, lang_bucket, COUNT(DISTINCT gkg_id) AS n_docs FROM e GROUP BY wk, lang_bucket
)
SELECT
  p.wk, p.lang_bucket, p.x, p.y, p.n, p.n_src, d1.nx, d2.nx AS ny, t.n_docs,
  SAFE_DIVIDE(
    LN(SAFE_DIVIDE(p.n * t.n_docs, d1.nx * d2.nx)), -LN(SAFE_DIVIDE(p.n, t.n_docs))
  ) AS npmi
FROM pairs AS p
JOIN tot AS t ON t.wk = p.wk AND t.lang_bucket = p.lang_bucket
JOIN deg AS d1 ON d1.wk = p.wk AND d1.lang_bucket = p.lang_bucket AND d1.ent = p.x
JOIN deg AS d2 ON d2.wk = p.wk AND d2.lang_bucket = p.lang_bucket AND d2.ent = p.y;
"""
    )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--lexicon", type=Path, default=LEXICON)
    args = ap.parse_args(argv)
    try:
        entries = load_entries(args.lexicon)
    except ValueError as err:
        print(err, file=sys.stderr)
        return 1
    S15.write_text(s15(entries, args.lexicon), encoding="utf-8")
    S16.write_text(s16(entries, args.lexicon), encoding="utf-8")
    print(f"{len(entries)} entries -> {S15.relative_to(REPO_ROOT)}, {S16.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
