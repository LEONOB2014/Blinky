"""The blind editor-test sheet (design, "Evaluation" / Editor test).

    RADAR_PROFILE=full uv run python -m models.editor_sheet            # writes the sheet + key
    RADAR_PROFILE=full uv run python -m models.editor_sheet --tally    # counts the filled sheet

Items: the radar's top 10 and the raw-count-growth top 10 for one week (default 2026-W42). A topic
on both lists is shown once and left out of the comparison (the overlap count is reported). The
order is shuffled with a fixed seed and the source list is hidden: the sheet goes to
`reports/editor_test.md`, the key (item -> list) to the git-ignored lake, so raters never see it.
Question: "¿Publicarías sobre este tema esta semana?" sí/no. The tally reports yes counts per list
with denominators, each rater separately.
"""

from __future__ import annotations

import argparse
import json
import random
import re
from pathlib import Path

import polars as pl

from models import backtest, build_scores
from radar.paths import REPO_ROOT, lake, profile

WEEK = "2026-W42"
SEED = 20261018
TOP_K = 10
RATERS = ("Evaluador A", "Evaluador B")
SHEET = REPO_ROOT / "reports" / "editor_test.md"


def key_path(week: str) -> Path:
    return lake() / "editor_test" / f"{week}_key.json"


def lists(week: str = WEEK) -> tuple[list[str], list[str]]:
    """The radar's and the raw-count-growth top 10 among the week's ranked universe."""
    s, raw, _ = backtest.scored_units()
    w = s.filter(pl.col("week") == week, pl.col("rank").is_not_null())
    if w.is_empty():
        raise ValueError(f"no scored units for {week}")
    radar = w.sort("rank").head(TOP_K)["unit_id"].to_list()
    rg = w.select("unit_id").join(raw.filter(pl.col("week") == week), on="unit_id")
    base = (
        rg.filter(pl.col("raw_growth").is_not_null())
        .sort(["raw_growth", "unit_id"], descending=[True, False])
        .head(TOP_K)["unit_id"]
        .to_list()
    )
    return radar, base


def items(radar: list[str], base: list[str]) -> list[dict]:
    """One item per distinct topic, shuffled with the fixed seed."""
    both = set(radar) & set(base)
    out = [{"topic_id": u, "list": "both" if u in both else "radar"} for u in radar]
    out += [{"topic_id": u, "list": "raw_count_growth"} for u in base if u not in both]
    random.Random(SEED).shuffle(out)  # noqa: S311 (a reproducible order, not cryptography)
    for i, it in enumerate(out, 1):
        it["item"] = i
    return out


def render(week: str, its: list[dict], labels: dict[str, str]) -> str:
    head = " | ".join(RATERS)
    lines = [
        f"# Prueba del editor: {week}",
        "",
        "Para cada tema, responde en tu columna **sí** o **no** a la pregunta:",
        "",
        "> ¿Publicarías sobre este tema esta semana en LinkedIn para ejecutivos de LatAm que "
        "aprenden IA?",
        "",
        "Responde sin consultar a nadie ni buscar la fuente: el orden es aleatorio y la lista de "
        "origen de cada tema está oculta. Escribe solo `sí` o `no`.",
        "",
        f"| # | Tema | {head} |",
        "|---|---|" + "---|" * len(RATERS),
    ]
    for it in its:
        blanks = " | ".join(" " for _ in RATERS)
        lines.append(f"| {it['item']} | {labels.get(it['topic_id'], it['topic_id'])} | {blanks} |")
    lines += [
        "",
        f"Generated by `models/editor_sheet.py` (seed {SEED}) on the `{profile()}` profile. The "
        "key is kept outside git; the tally (`--tally`) reports yes counts per list with "
        "denominators, each rater separately, and the number of topics on both lists, which are "
        "left out of the comparison. Small sample: read the counts, not a percentage.",
    ]
    return "\n".join(lines) + "\n"


def write(week: str = WEEK) -> list[dict]:
    radar, base = lists(week)
    its = items(radar, base)
    names, _ = build_scores.labels_and_mapped()
    labels = {it["topic_id"]: build_scores.label(names, it["topic_id"]) for it in its}
    if profile() != "full":
        print(render(week, its, labels))  # noqa: T201
        return its
    SHEET.write_text(render(week, its, labels), encoding="utf-8")
    kp = key_path(week)
    kp.parent.mkdir(parents=True, exist_ok=True)
    kp.write_text(json.dumps({"week": week, "seed": SEED, "items": its}, indent=2), "utf-8")
    print(f"wrote {SHEET} and {kp}")  # noqa: T201
    return its


ROW = re.compile(r"^\|\s*(\d+)\s*\|[^|]*\|(.*)\|\s*$")


def tally(sheet: str, key: list[dict]) -> dict:
    """Yes counts per list and rater from a filled sheet; topics on both lists are left out."""
    by_item = {it["item"]: it["list"] for it in key}
    answers: dict[int, list[str]] = {}
    for line in sheet.splitlines():
        m = ROW.match(line)
        if m:
            answers[int(m.group(1))] = [c.strip().lower() for c in m.group(2).split("|")]
    out = {"overlap": sum(1 for v in by_item.values() if v == "both"), "raters": {}}
    for j, rater in enumerate(RATERS):
        counts = {"radar": [0, 0], "raw_count_growth": [0, 0]}
        for item, src in by_item.items():
            if src == "both":
                continue
            a = answers.get(item, [])
            ans = a[j] if j < len(a) else ""
            if ans in ("sí", "si", "no"):
                counts[src][1] += 1
                counts[src][0] += ans in ("sí", "si")
        out["raters"][rater] = {k: f"{v[0]}/{v[1]}" for k, v in counts.items()}
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--week", default=WEEK)
    ap.add_argument("--tally", action="store_true")
    args = ap.parse_args(argv)
    if args.tally:
        key = json.loads(key_path(args.week).read_text("utf-8"))["items"]
        print(json.dumps(tally(SHEET.read_text("utf-8"), key), ensure_ascii=False, indent=2))  # noqa: T201
        return 0
    write(args.week)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
